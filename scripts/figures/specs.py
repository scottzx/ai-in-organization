def flow_marks(steps, marks, legend, feedback=None, base=None, branches=None, box_h=1.5):
    """横向流程＋问题位置（强调色框在步骤下方）。branches: {步骤序号: [分支文字, ...]}，画在流程上方。"""
    n = len(steps); gap = 0.4; m = 0.15; bw = (LW - 2 * m - gap * (n - 1)) / n
    top = (1.0 if feedback else 0) + (1.85 if branches else 0)
    bh_base = base_h(base) if base else 0
