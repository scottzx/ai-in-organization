w, g = 'white', 'grey'

def miit_topo(p):
    """四层网络拓扑（行业/企业/厂站/设备）。左栏功能体系与右侧网络拓扑合并为每层若干行；设备图标改为文字框。文字全部由 p 传入。"""
    w = 'white'; g = 'grey'
    def items(xs, st=w): return [(x, st) for x in xs]
    def split(xs, k): return [xs[i:i + k] for i in range(0, len(xs), k)]
    bands = []
    for L in p['layers']:
        fs = L.get('funcs', [])   # 功能体系：平台后至多 3 项一行，余下另起一行
        rows = ([[(L['plat'], 'plat')] + items(fs[:3], g)] + ([items(fs[3:], g)] if fs[3:] else [])) if L.get('plat') else ([items(fs, g)] if fs else [])
        for k, xs in L.get('systems', []):
            rows += [items(c) for c in split(xs, k)]
        for r in L.get('rows', []):
            rows.append([(t, st) for t, st in r])
        for t, xs in L.get('devices', []):
            rows.append([(t, 'head')] + items(xs))
        bands.append((L['name'], rows))
    return net3(bands)

